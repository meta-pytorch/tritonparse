class _HookEvent(Enum):
    POST_TRACE = "post_trace"
    POST_COMPILE = "post_compile"


class FakeHooks:
    """Stand-in for the upstream `cutlass.hooks` API (NVIDIA/cutlass#3697)."""

    HookEvent = _HookEvent

    def __init__(self):
        self.registrations = []

    def register_hook(self, event, hook, *, dsl):
        self.registrations.append((event, hook, dsl))

    def remove_hook(self, event, hook, *, dsl):
        self.registrations.remove((event, hook, dsl))


def _fake_cutlass_module(dsl, hooks=None):
    cutlass_mod = MagicMock(name="cutlass")
    cutlass_mod.cutlass_dsl.CuTeDSL._get_dsl.return_value = dsl
    cutlass_mod.hooks = hooks
    return cutlass_mod


class SetupTeardownTest(unittest.TestCase):
    def setUp(self):
        cutedsl_logging._reset_for_tests()
        self.addCleanup(cutedsl_logging._reset_for_tests)
        self._env_patcher = patch.dict(os.environ, {}, clear=False)
        self._env_patcher.start()
        os.environ.pop("CUTE_DSL_LINEINFO", None)
        os.environ.pop("CUTE_DSL_DUMP_DIR", None)
        self.addCleanup(self._env_patcher.stop)

    def test_setup_registers_and_teardown_removes(self):
        dsl, hooks = FakeDSL(), FakeHooks()
        with patch.dict(sys.modules, {"cutlass": _fake_cutlass_module(dsl, hooks)}):
            self.assertTrue(cutedsl_logging.setup_cutedsl_tracing())
            self.assertEqual(
                hooks.registrations,
                [
                    (
                        _HookEvent.POST_COMPILE,
                        cutedsl_logging._compilation_hook,
                        dsl,
                    )
                ],
            )
            self.assertTrue(dsl.envar.keep_ir)
            self.assertTrue(dsl.envar.lineinfo)
            # Idempotent.
            self.assertTrue(cutedsl_logging.setup_cutedsl_tracing())
            self.assertEqual(len(hooks.registrations), 1)
            cutedsl_logging.teardown_cutedsl_tracing()
            self.assertEqual(hooks.registrations, [])
            # Teardown gives CuTeDSL its own settings back.
            self.assertEqual(vars(dsl.envar), vars(_fake_envar()))

    def test_setup_without_cutlass_is_noop(self):
        # None in sys.modules makes the import fail even where cutlass exists.
        with patch.dict(sys.modules, {"cutlass": None}):
            # clear_logging_config's teardown path must also survive.
            self.assertFalse(cutedsl_logging.setup_cutedsl_tracing())
            cutedsl_logging.teardown_cutedsl_tracing()

    def test_setup_with_old_cutlass_warns(self):
        dsl_without_api = object()
        with patch.dict(
            sys.modules, {"cutlass": _fake_cutlass_module(dsl_without_api)}
        ):
            with self.assertLogs("tritonparse.cutedsl_logging", level="WARNING") as cm:
                self.assertFalse(cutedsl_logging.setup_cutedsl_tracing())
            self.assertTrue(
                any("POST_COMPILE" in line for line in cm.output), cm.output
            )


class HookExceptionIsolationTest(unittest.TestCase):
    """A tracing failure must not reach the traced compile/launch: upstream
    wraps hook exceptions as `DSLRuntimeError`, and a `PRE_EXECUTE` failure
    stops the call, so the hook adapters contain their own failures."""

    def setUp(self):
        cutedsl_logging._reset_for_tests()
        self.addCleanup(cutedsl_logging._reset_for_tests)

    def test_compilation_hook_swallows_tracing_failure(self):
        event = SimpleNamespace(
            owner=object(),
            function_name="kernel_cutlass_mk_abc123",
            module_hash="deadbeef0123",
            cache_hit=False,
            artifacts=None,
            compile_options=None,
            func_body=None,
            kernel_info=None,
        )
        with (
            patch.object(
                cutedsl_logging,
                "maybe_trace_cutedsl",
                side_effect=RuntimeError("boom"),
            ),
            self.assertLogs("tritonparse.cutedsl_logging", level="WARNING") as cm,
        ):
            cutedsl_logging._compilation_hook(event)
        self.assertTrue(
            any("compilation tracing failed" in line for line in cm.output),
            cm.output,
        )

    def test_teardown_unregisters_even_if_envar_restore_fails(self):
        # teardown documents "Never raises": a failing envar restore must
        # not skip hook unregistration (which would leave hooks installed
        # and let a later setup register duplicates).
        removed = []
        cutedsl_logging._CUTEDSL_UNREGISTER.append(lambda: removed.append(True))
        with (
            patch.object(
                cutedsl_logging,
                "_restore_cutedsl_envar",
                side_effect=RuntimeError("read-only attr"),
            ),
            self.assertLogs("tritonparse.cutedsl_logging", level="WARNING"),
        ):
            cutedsl_logging.teardown_cutedsl_tracing()
        self.assertEqual(removed, [True])

    def test_launch_hook_swallows_tracing_failure(self):
        event = SimpleNamespace(
            owner=object(),
            function_name="kernel_cutlass_mk_abc123",
            module_hash="deadbeef0123",
            kernel_info=None,
            args=(),
            kwargs={},
            exe_args=None,
            executor=None,
            arg_names=(),
        )
        with (
            patch.object(
                cutedsl_logging,
                "maybe_trace_cutedsl_launch",
                side_effect=RuntimeError("boom"),
            ),
            self.assertLogs("tritonparse.cutedsl_logging", level="WARNING") as cm,
        ):
            cutedsl_logging._launch_hook(event)
        self.assertTrue(
            any("launch tracing failed" in line for line in cm.output), cm.output
        )


class CuteDSLAdapterTest(unittest.TestCase):
    def test_resolve_from_backend_name(self):
        adapter = get_backend_registry().resolve_from_backend_name("cutedsl")
        self.assertIsInstance(adapter, CuteDSLAdapter)

    def test_resolve_from_backend_name_mixed_case(self):
        adapter = get_backend_registry().resolve_from_backend_name("CuTeDSL")
        self.assertIsInstance(adapter, CuteDSLAdapter)

    def test_resolve_from_trace(self):
        adapter = get_backend_registry().resolve_from_trace({"backend_name": "cutedsl"})
        self.assertIsInstance(adapter, CuteDSLAdapter)

    def test_resolve_by_exact_name(self):
        registry = get_backend_registry()
        adapter = registry.resolve_from_backend_name("cutedsl")
        self.assertEqual(adapter.adapter_name, "cutedsl")
        self.assertIs(registry.resolve(adapter_name="cutedsl"), adapter)
        # Triton runtime backends still resolve to their "_triton" adapters.
        self.assertIsInstance(
            registry.resolve_from_backend_name("cuda"), NvidiaTritonAdapter
        )
        # Unknown backends still raise (no silent mis-resolution).
        with self.assertRaises(ValueError):
            registry.resolve_from_backend_name("cutedsl_typo")

    def test_stages(self):
        adapter = get_backend_registry().resolve_from_backend_name("cutedsl")
        stages = {s.name: s for s in adapter.list_ir_stages()}
        self.assertEqual(
            sorted(stages), ["clean_mlir", "cubin", "json", "mlir", "ptx", "sass"]
        )
        for name in ("mlir", "clean_mlir"):
            stage = stages[name]
            self.assertEqual(stage.extension, f".{name}")
            self.assertEqual(stage.parser_id, "generic_loc")
            self.assertEqual(stage.syntax_id, "mlir")
            self.assertTrue(stage.supports_source_mapping)
        self.assertEqual(stages["ptx"].parser_id, "ptx_loc")
        self.assertEqual(stages["sass"].parser_id, "sass_loc")

    def test_sass_derived_from_cubin(self):
        adapter = get_backend_registry().resolve_from_backend_name("cutedsl")
        infos = adapter.list_applicable_derived_artifacts({"sass"})
        self.assertEqual(
            [(i.target_stage_name, i.source_stage_name, i.tool_name) for i in infos],
            [("sass", "cubin", "nvdisasm")],
        )


class CutedslEndToEndTest(unittest.TestCase):
    """Hook -> NDJSON file -> schema validation -> parse."""

    def setUp(self):
        self.tmp_dir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp_dir, True)

    def tearDown(self):
        # triton/cutlass are not dependencies of this target; clear only
        # touches them to null out hooks that were never installed here.
        with patch.dict(sys.modules, {"triton": MagicMock(), "cutlass": MagicMock()}):
            structured_logging.clear_logging_config()

    def _emit_event(self):
        structured_logging.init_basic(trace_folder=self.tmp_dir)
        _trace_compilation(
            artifacts=SimpleNamespace(
                MLIR=SAMPLE_CLEAN_MLIR, MLIR_RAW=SAMPLE_MLIR, PTX=SAMPLE_PTX, CUBIN=None
            )
        )
        structured_logging.TRITON_TRACE_HANDLER._ensure_stream_closed()
        paths = sorted(
            glob.glob(os.path.join(self.tmp_dir, "dedicated_log_triton_trace_*"))
        )
        self.assertEqual(len(paths), 1)
        with open(paths[0]) as f:
            lines = [line for line in f.read().split("\n") if line.strip()]
        self.assertEqual(len(lines), 1)
        return json.loads(lines[0])

    def test_emitted_event_validates(self):
        event = self._emit_event()
        ok, errors = validate_record(event)
        self.assertTrue(ok, errors)
        self.assertEqual(event["event_type"], "compilation")
        self.assertIn("timestamp", event)
        self.assertEqual(event["payload"]["metadata"]["cluster_dims"], [2, 1, 1])

    def test_parse_produces_mlir_mappings(self):
        event = self._emit_event()
        # Point the payload's python source at the MLIR's referenced file so
        # the python mapping has something to join (paths need not exist).
        event["payload"]["python_source"]["file_path"] = "/fake/wd/kernel.py"
        out = parse_single_trace_content(dumps(event))
        parsed = json.loads(out)
        payload = parsed["payload"]
        stage_names = [s["name"] for s in payload["ir_stages"]]
        self.assertEqual(
            stage_names, ["mlir", "clean_mlir", "ptx", "cubin", "sass", "json"]
        )
        for name in ("mlir", "clean_mlir"):
            stage = next(s for s in payload["ir_stages"] if s["name"] == name)
            self.assertEqual(stage["syntax_id"], "mlir")
            mappings = payload["source_mappings"][name]
            self.assertTrue(len(mappings) > 0, name)
            files = {m["file"] for m in mappings.values()}
            self.assertEqual(files, {"/fake/wd/kernel.py"})
        self.assertTrue(len(payload["source_mappings"]["python"]) > 0)


if __name__ == "__main__":
    unittest.main()

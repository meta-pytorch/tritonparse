class CutedslEnvarTest(unittest.TestCase):
    def setUp(self):
        cutedsl_logging._reset_for_tests()
        self.addCleanup(cutedsl_logging._reset_for_tests)
        env_patcher = patch.dict(os.environ)
        env_patcher.start()
        self.addCleanup(env_patcher.stop)
        os.environ.pop("CUTE_DSL_LINEINFO", None)
        os.environ.pop("CUTE_DSL_DUMP_DIR", None)

    def _configure(self, envar):
        cutedsl_logging._configure_cutedsl_envar(SimpleNamespace(envar=envar))

    def test_configure_and_restore(self):
        envar = _fake_envar()
        self._configure(envar)
        for attr in cutedsl_logging.CUTEDSL_KEEP_ATTRS:
            self.assertTrue(getattr(envar, attr), attr)
        self.assertFalse(envar.keep_sass)
        self.assertTrue(envar.lineinfo)
        # Nothing kept by the user: files go to a private temporary directory.
        temp_dir = envar.dump_dir
        self.assertNotEqual(temp_dir, "/user/cwd")
        self.assertTrue(os.path.isdir(temp_dir))
        cutedsl_logging._restore_cutedsl_envar()
        self.assertEqual(vars(envar), vars(_fake_envar()))
        self.assertFalse(os.path.exists(temp_dir))

    def test_user_keep_keeps_dump_dir(self):
        envar = _fake_envar(keep_ptx=True, dump_dir="/user/dump")
        self._configure(envar)
        self.assertEqual(envar.dump_dir, "/user/dump")
        self.assertTrue(envar.keep_ir)
        self.assertTrue(envar.keep_cubin)
        cutedsl_logging._restore_cutedsl_envar()
        self.assertEqual(
            vars(envar), vars(_fake_envar(keep_ptx=True, dump_dir="/user/dump"))
        )

    def test_user_dump_dir_respected(self):
        os.environ["CUTE_DSL_DUMP_DIR"] = "/user/dump"
        envar = _fake_envar(dump_dir="/user/dump")
        self._configure(envar)
        self.assertEqual(envar.dump_dir, "/user/dump")
        self.assertTrue(envar.keep_ir)

    def test_explicit_lineinfo_off_respected(self):
        os.environ["CUTE_DSL_LINEINFO"] = "0"
        envar = _fake_envar()
        self._configure(envar)
        self.assertFalse(envar.lineinfo)

    def test_loc_tracebacks_keeps_lineinfo_off(self):
        envar = _fake_envar(loc_tracebacks=1)
        with self.assertLogs("tritonparse.cutedsl_logging", level="WARNING") as cm:
            self._configure(envar)
        self.assertFalse(envar.lineinfo)
        self.assertTrue(envar.keep_ir)
        self.assertTrue(
            any("CUTE_DSL_LOC_TRACEBACKS" in line for line in cm.output), cm.output
        )

    def test_missing_envar_warns(self):
        with self.assertLogs("tritonparse.cutedsl_logging", level="WARNING") as cm:
            cutedsl_logging._configure_cutedsl_envar(SimpleNamespace())
        self.assertTrue(
            any("CUTE_DSL_KEEP=ir-debug,ir,ptx,cubin" in line for line in cm.output),
            cm.output,
        )
        self.assertIsNone(cutedsl_logging._CUTEDSL_ENVAR_RESTORE)



# Minimal CuTe-dialect MLIR in the real dumped style (standard #loc defs when
# CUTE_DSL_LINEINFO=1; verified against CuTeDSL 4.6.2 output).
SAMPLE_MLIR = """module attributes {gpu.container_module} {
  %iter = cute.get_iter(%arg0) : !cute.memref loc(#loc1)
  %lay = cute.get_layout(%arg0) : !cute.memref loc(#loc2)
}
#loc1 = loc("/fake/wd/kernel.py":10:4)
#loc2 = loc("/fake/wd/kernel.py":12:8)
#loc3 = loc("mkernel"(#loc1))
"""

SAMPLE_PTX = """//
// Generated by NVIDIA NVVM Compiler
.version 8.5
.target sm_90a
.address_size 64
"""


# Host function configuring and launching one kernel, in the dumped style
# (verified against CuTeDSL 4.6.2 output). The kernel's own %0 is a constant,
# while the host's %0 depends on a runtime argument.
HOST_MLIR_TEMPLATE = """module attributes {gpu.container_module} {
  gpu.module @kernels {
    cuda.kernel @mkernel(%arg0: i32) attributes {cute.kernel} {
      %0 = arith.constant 64 : i32 loc(#loc1)
      cuda.return loc(#loc1)
    } loc(#loc1)
  } loc(#loc1)
  func.func @cutlass_mk(%arg0: i32, %arg1: i32) -> i32 attributes {llvm.emit_c_interface} {
    %c128_i32 = arith.constant 128 : i32 loc(#loc1)
    %c1_i32 = arith.constant 1 : i32 loc(#loc1)
    %c2_i32 = arith.constant 2 : i32 loc(#loc1)
    %c8_i32 = arith.constant 8 : i32 loc(#loc1)
    %0 = arith.ceildivsi %arg1, %c128_i32 : i32 loc(#loc1)
    %4 = cuda.launch_cfg.create<max_attrs = 17 : i32> (blockDim = (%c128_i32, %c1_i32, %c1_i32), dynamicSmemBytes = %arg0, gridDim = (GRID_DIMS), stream = %3) : i32, i32, i32, i64, i32, i32, i32, !cuda.stream -> !cuda.launch_cfg<max_attrs = 17> loc(#loc2)
CLUSTER_LINE    %5 = cuda.launch_ex @kernels::@mkernel<%4> (%arg0) {assume_kernel_attr = #cuda.assume_kernel_attr<true>} : !cuda.launch_cfg<max_attrs = 17>, (i32) -> !cuda.result loc(#loc2)
    return %c1_i32 : i32 loc(#loc2)
  } loc(#loc2)
}
#loc1 = loc("/fake/wd/kernel.py":20:4)
#loc2 = loc("/fake/wd/kernel.py":22:8)
"""


def _host_mlir(grid="%c8_i32, %c1_i32, %c1_i32", cluster=None):
    cluster_line = (
        f"    cuda.launch_cfg.cluster_dim[%4] ({cluster}) : "
        "!cuda.launch_cfg<max_attrs = 17>, i32, i32, i32 loc(#loc2)\n"
        if cluster
        else ""
    )
    return HOST_MLIR_TEMPLATE.replace("GRID_DIMS", grid).replace(
        "CLUSTER_LINE", cluster_line
    )


SAMPLE_CLEAN_MLIR = _host_mlir(cluster="%c2_i32, %c1_i32, %c1_i32")

TWO_LAUNCH_MLIR = """func.func @host() {
    %c1_i32 = arith.constant 1 : i32
    %c4_i32 = arith.constant 4 : i32
    %0 = cuda.launch_cfg.create<max_attrs = 17 : i32> (blockDim = (%c4_i32, %c1_i32, %c1_i32), dynamicSmemBytes = %c1_i32, gridDim = (%c4_i32, %c1_i32, %c1_i32), stream = %s) : i32, i32, i32, i64, i32, i32, i32, !cuda.stream -> !cuda.launch_cfg<max_attrs = 17>
    %1 = cuda.launch_ex @kernels::@first<%0> () : !cuda.launch_cfg<max_attrs = 17>, () -> !cuda.result
    %2 = cuda.launch_cfg.create<max_attrs = 17 : i32> (blockDim = (%c1_i32, %c1_i32, %c1_i32), dynamicSmemBytes = %c1_i32, gridDim = (%c1_i32, %c4_i32, %c1_i32), stream = %s) : i32, i32, i32, i64, i32, i32, i32, !cuda.stream -> !cuda.launch_cfg<max_attrs = 17>
    %3 = cuda.launch_ex @kernels::@second<%2> () : !cuda.launch_cfg<max_attrs = 17>, () -> !cuda.result
}
"""


def _fake_artifacts(mlir=SAMPLE_MLIR, ptx=SAMPLE_PTX, cubin=None, clean_mlir=None):
    # Upstream `JitFunctionArtifacts`: `MLIR` holds the clean IR when it is
    # kept (otherwise the raw IR), and `MLIR_RAW` holds the raw dump.
    if clean_mlir is None:
        return SimpleNamespace(MLIR=mlir, MLIR_RAW=mlir, PTX=ptx, CUBIN=cubin)
    return SimpleNamespace(MLIR=clean_mlir, MLIR_RAW=mlir, PTX=ptx, CUBIN=cubin)


def _fake_options(gpu_arch="sm_90a"):
    return SimpleNamespace(gpu_arch=gpu_arch)


def _trace_compilation(**overrides):
    kwargs = {
        "function_name": "kernel_cutlass_mk_abc123",
        "module_hash": "deadbeef0123",
        "cache_hit": False,
        "artifacts": _fake_artifacts(),
        "compile_options": _fake_options(),
        "func_body": _sample_kernel_fn,
        "kernel_info": {"mkernel": {"max_dynamic_shared_size_bytes": 0}},
    }
    kwargs.update(overrides)
    return cutedsl_logging.maybe_trace_cutedsl(object(), **kwargs)


class MaybeTraceCutedslTest(unittest.TestCase):
    def setUp(self):
        cutedsl_logging._reset_for_tests()
        self.addCleanup(cutedsl_logging._reset_for_tests)

    def test_payload_shape(self):
        trace_data = _trace_compilation()
        metadata = trace_data["metadata"]
        self.assertEqual(metadata["backend_name"], "cutedsl")
        self.assertEqual(metadata["hash"], "deadbeef0123")
        self.assertEqual(metadata["name"], "kernel_cutlass_mk_abc123")
        self.assertFalse(metadata["cache_hit"])
        self.assertEqual(metadata["arch"], "sm_90a")
        self.assertEqual(metadata["kernel_names"], ["mkernel"])
        file_content = trace_data["file_content"]
        self.assertEqual(file_content["kernel.mlir"], SAMPLE_MLIR)
        self.assertEqual(file_content["kernel.ptx"], SAMPLE_PTX)
        self.assertNotIn("kernel.cubin", file_content)
        self.assertNotIn("kernel.clean_mlir", file_content)
        python_source = trace_data["python_source"]
        self.assertTrue(
            python_source["file_path"].endswith("test_cutedsl_compilation.py")
        )
        self.assertIn("def _sample_kernel_fn", python_source["code"])

    def test_cache_hit_and_missing_hash(self):
        trace_data = _trace_compilation(cache_hit=True, module_hash=None)
        self.assertTrue(trace_data["metadata"]["cache_hit"])
        # Schema requires metadata.hash: falls back to the kernel name.
        self.assertEqual(trace_data["metadata"]["hash"], "kernel_cutlass_mk_abc123")

    def test_clean_mlir_recorded(self):
        trace_data = _trace_compilation(
            artifacts=_fake_artifacts(clean_mlir=SAMPLE_CLEAN_MLIR)
        )
        file_content = trace_data["file_content"]
        self.assertEqual(file_content["kernel.mlir"], SAMPLE_MLIR)
        self.assertEqual(file_content["kernel.clean_mlir"], SAMPLE_CLEAN_MLIR)

    def test_clean_only_dump_not_duplicated(self):
        # With only the clean dump kept, CuTeDSL reports it as MLIR too.
        trace_data = _trace_compilation(
            artifacts=_fake_artifacts(
                mlir=SAMPLE_CLEAN_MLIR, clean_mlir=SAMPLE_CLEAN_MLIR
            )
        )
        file_content = trace_data["file_content"]
        self.assertEqual(file_content["kernel.mlir"], SAMPLE_CLEAN_MLIR)
        self.assertNotIn("kernel.clean_mlir", file_content)

    def test_current_mlir_artifacts(self):
        cases = (
            (
                "both",
                SAMPLE_CLEAN_MLIR,
                SAMPLE_MLIR,
                {"kernel.mlir": SAMPLE_MLIR, "kernel.clean_mlir": SAMPLE_CLEAN_MLIR},
            ),
            ("clean_only", SAMPLE_CLEAN_MLIR, None, {"kernel.mlir": SAMPLE_CLEAN_MLIR}),
            ("raw_only", SAMPLE_MLIR, SAMPLE_MLIR, {"kernel.mlir": SAMPLE_MLIR}),
            ("raw_without_mlir", None, SAMPLE_MLIR, {"kernel.mlir": SAMPLE_MLIR}),
            ("neither", None, None, {}),
        )
        for name, mlir, raw_mlir, expected in cases:
            with self.subTest(case=name):
                trace_data = _trace_compilation(
                    artifacts=SimpleNamespace(
                        MLIR=mlir, MLIR_RAW=raw_mlir, PTX=None, CUBIN=None
                    )
                )
                self.assertEqual(trace_data.get("file_content", {}), expected)

    def test_binary_cubin_skipped_with_flag(self):
        trace_data = _trace_compilation(artifacts=_fake_artifacts(cubin=b"\x7fELF..."))
        self.assertNotIn("kernel.cubin", trace_data["file_content"])
        self.assertTrue(trace_data["metadata"]["has_cubin"])

    def test_missing_artifacts_and_source(self):
        trace_data = _trace_compilation(artifacts=None, func_body=None)
        self.assertNotIn("file_content", trace_data)
        self.assertNotIn("python_source", trace_data)
        # Still emits: metadata-only compilation event.
        self.assertEqual(trace_data["metadata"]["hash"], "deadbeef0123")

    def test_path_like_artifact_is_read(self):
        with tempfile.NamedTemporaryFile(mode="w", suffix=".mlir", delete=False) as f:
            f.write(SAMPLE_MLIR)
            path = f.name
        self.addCleanup(os.unlink, path)
        trace_data = _trace_compilation(artifacts=_fake_artifacts(mlir=path, ptx=None))
        # Upstream leaves the raw path when the file was missing at
        # construction; resolve it instead of recording the path as code.
        self.assertEqual(trace_data["file_content"]["kernel.mlir"], SAMPLE_MLIR)

    def test_dangling_path_artifact_dropped(self):
        trace_data = _trace_compilation(
            artifacts=_fake_artifacts(mlir="/nonexistent/kernel.mlir", ptx=None)
        )
        self.assertNotIn("file_content", trace_data)

    def test_allowlist_filtering(self):
        with patch.object(
            structured_logging, "_KERNEL_ALLOWLIST_PATTERNS", ["other_*"]
        ):
            self.assertEqual(_trace_compilation(), {})
        with patch.object(
            structured_logging, "_KERNEL_ALLOWLIST_PATTERNS", ["kernel_cutlass_*"]
        ):
            self.assertIn("metadata", _trace_compilation())

    def test_full_python_source_mode(self):
        set_runtime_full_python_source_override(True)
        self.addCleanup(set_runtime_full_python_source_override, None)
        trace_data = _trace_compilation()
        python_source = trace_data["python_source"]
        self.assertEqual(python_source["start_line"], 1)
        # Full-file capture contains helpers outside the kernel function.
        self.assertIn("SAMPLE_MLIR", python_source["code"])
        self.assertIn("function_start_line", python_source)


class LaunchConfigTest(unittest.TestCase):
    def setUp(self):
        cutedsl_logging._reset_for_tests()
        self.addCleanup(cutedsl_logging._reset_for_tests)

    def test_parse_static_launch(self):
        configs = cutedsl_logging.parse_cutedsl_launch_configs(SAMPLE_CLEAN_MLIR)
        self.assertEqual(
            configs,
            [
                {
                    "kernel": "mkernel",
                    "block": [128, 1, 1],
                    "grid": [8, 1, 1],
                    "cluster": [2, 1, 1],
                }
            ],
        )

    def test_parse_dynamic_dims_resolved_per_function(self):
        # The kernel's constant %0 must not leak into the host function.
        configs = cutedsl_logging.parse_cutedsl_launch_configs(
            _host_mlir(grid="%0, %c1_i32, %c1_i32")
        )
        self.assertEqual(configs[0]["grid"], [None, 1, 1])
        self.assertNotIn("cluster", configs[0])

    def test_parse_without_launches(self):
        self.assertEqual(cutedsl_logging.parse_cutedsl_launch_configs(SAMPLE_MLIR), [])

    def test_compilation_records_launch_configs_and_grid(self):
        trace_data = _trace_compilation(
            artifacts=_fake_artifacts(clean_mlir=SAMPLE_CLEAN_MLIR)
        )
        metadata = trace_data["metadata"]
        self.assertEqual(metadata["launch_configs"][0]["grid"], [8, 1, 1])
        self.assertEqual(metadata["cluster_dims"], [2, 1, 1])
        self.assertEqual(
            cutedsl_logging._STATIC_GRID_BY_HASH, {"deadbeef0123": [8, 1, 1]}
        )

    def test_clean_mlir_preferred_for_launch_configs(self):
        trace_data = _trace_compilation(
            artifacts=_fake_artifacts(
                mlir=_host_mlir(grid="%0, %c1_i32, %c1_i32"),
                clean_mlir=_host_mlir(),
            )
        )
        self.assertEqual(trace_data["metadata"]["launch_configs"][0]["grid"], [8, 1, 1])

    def test_current_mlir_preferred_over_raw_for_launch_configs(self):
        raw_mlir = _host_mlir(grid="%0, %c1_i32, %c1_i32")
        trace_data = _trace_compilation(
            artifacts=SimpleNamespace(
                MLIR=_host_mlir(), MLIR_RAW=raw_mlir, PTX=None, CUBIN=None
            )
        )
        self.assertEqual(trace_data["file_content"]["kernel.mlir"], raw_mlir)
        self.assertEqual(trace_data["metadata"]["launch_configs"][0]["grid"], [8, 1, 1])
        self.assertEqual(
            cutedsl_logging._STATIC_GRID_BY_HASH, {"deadbeef0123": [8, 1, 1]}
        )

    def test_dynamic_grid_not_remembered(self):
        trace_data = _trace_compilation(
            artifacts=_fake_artifacts(
                clean_mlir=_host_mlir(grid="%0, %c1_i32, %c1_i32")
            )
        )
        # No cluster_dim op: the default 1x1x1 cluster.
        self.assertEqual(trace_data["metadata"]["cluster_dims"], [1, 1, 1])
        self.assertEqual(cutedsl_logging._STATIC_GRID_BY_HASH, {})

    def test_multiple_launches_not_remembered(self):
        trace_data = _trace_compilation(
            artifacts=_fake_artifacts(clean_mlir=TWO_LAUNCH_MLIR)
        )
        configs = trace_data["metadata"]["launch_configs"]
        self.assertEqual([c["kernel"] for c in configs], ["first", "second"])
        self.assertEqual([c["grid"] for c in configs], [[4, 1, 1], [1, 4, 1]])
        self.assertEqual(cutedsl_logging._STATIC_GRID_BY_HASH, {})


class CutedslSassTest(unittest.TestCase):
    CUBIN = b"\x7fELF fake cubin"

    def setUp(self):
        structured_logging._logged_derived_artifact_failures.clear()
        self.addCleanup(structured_logging._logged_derived_artifact_failures.clear)
        self.adapter = get_backend_registry().resolve_from_backend_name("cutedsl")

    def _trace_with(self, enabled, derive_func):
        info = DerivedArtifactInfo("sass", "cubin", "nvdisasm", derive_func)
        with (
            patch(
                "tritonparse.shared_vars.get_enabled_derived_artifacts",
                return_value=enabled,
            ),
            patch.object(
                self.adapter, "list_applicable_derived_artifacts", return_value=[info]
            ),
        ):
            return _trace_compilation(artifacts=_fake_artifacts(cubin=self.CUBIN))

    def test_sass_off_by_default(self):
        derive = MagicMock(return_value="SASS")
        trace_data = self._trace_with(set(), derive)
        derive.assert_not_called()
        self.assertNotIn("kernel.sass", trace_data["file_content"])

    def test_sass_derived_from_cubin_bytes(self):
        seen = {}

        def derive(path):
            with open(path, "rb") as f:
                seen["cubin"] = f.read()
            seen["path"] = path
            return "Function:mkernel\n"

        trace_data = self._trace_with({"sass"}, derive)
        self.assertEqual(
            trace_data["file_content"]["kernel.sass"], "Function:mkernel\n"
        )
        self.assertEqual(seen["cubin"], self.CUBIN)
        # The temporary copy is gone once the event is traced.
        self.assertFalse(os.path.exists(seen["path"]))

    def test_sass_failure_leaves_placeholder(self):
        derive = MagicMock(side_effect=FileNotFoundError("nvdisasm"))
        with self.assertLogs("tritonparse.structured_logging", level="WARNING"):
            trace_data = self._trace_with({"sass"}, derive)
        file_content = trace_data["file_content"]
        self.assertTrue(
            file_content["kernel.sass"].startswith("<error dumping derived artifact"),
            file_content["kernel.sass"],
        )
        # The failure does not cost the rest of the event.
        self.assertEqual(file_content["kernel.ptx"], SAMPLE_PTX)


